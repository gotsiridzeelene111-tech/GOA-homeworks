# გამოიყენეთ შედარების ოპერატორები და დაწერეთ კოდი, რომელიც დააბრუნებს შესაბამის შედეგს:

# შეამოწმეთ, უდრის თუ არა 25 რიცხვი 25-ს.
print(25 == 25)
# შეამოწმეთ, მეტია თუ არა 100 რიცხვი 50-ზე.
print(100 > 50)
# შეამოწმეთ, ნაკლებია თუ არა 7 რიცხვი 3-ზე.
print(7 < 3)
# შეამოწმეთ, უდრის თუ არა 15 რიცხვი 20-ს.
print(15 == 20)
# შეამოწმეთ, არის თუ არა 30 მეტი ან ტოლი 30-ის.
print(30 >= 30)
# შეამოწმეთ, არის თუ არა 12 ნაკლები ან ტოლი 10-ის.
print(12 <= 10)
# დავალება 3 — შეავსე გამოტოვებული ადგილები

# ჩასვით შესაბამისი ოპერატორი: ==, !=, <, >, <=, >=.

# print(10 == 10) → True

# print(5 < 10) → True

# print(20 > 15) → True

# print(7 != 7) → False

# print(4 < 9) → True

# print(12 < 10) → False

# დავალება 4 — გამოიყენე AND

# დაწერეთ პროგრამები შემდეგი პირობებით:

# შეამოწმეთ, არის თუ არა 20 მეტი 10-ზე და 30 მეტი 20-ზე.
print(20 > 10 and 30 > 20)
# შეამოწმეთ, უდრის თუ არა 15 რიცხვი 15-ს და 10 ნაკლებია თუ არა 5-ზე.
print(15 == 15 and 10 < 5)
# შეამოწმეთ, არის თუ არა 50 მეტი 40-ზე და 100 უდრის თუ არა 100-ს.
print(50 > 40 and 100 == 100)
# შეამოწმეთ, არის თუ არა 8 ნაკლები 5-ზე და 10 მეტი 3-ზე.
print(8 < 5 and 10 > 3)